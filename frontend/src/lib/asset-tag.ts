/**
 * เรื่องแบบไหนที่ควรถามเลขทรัพย์สิน (Asset tag)
 *
 * ช่องนี้เคยแสดงทุกเรื่อง ผลคือผู้แจ้งเรื่อง "ขอสิทธิ์ใช้ VPN" หรือ "ลืมรหัสผ่าน"
 * ต้องมองข้ามช่องที่ไม่เกี่ยวกับเรื่องของตัวเอง และบางคนกรอกเลขเครื่องที่ตัวเองใช้ลงไปเฉย ๆ
 * ทำให้ข้อมูลในช่องนี้ปนกันระหว่าง "เครื่องที่เสีย" กับ "เครื่องที่ผู้แจ้งนั่งอยู่"
 *
 * ตัดสินจาก **รหัสหมวด** ไม่ใช่ชื่อที่แสดง เพราะชื่อแปลได้และผู้ดูแลแก้ได้จากหน้าจอ
 * ส่วนรหัสถูกล็อกไว้ — migration ห้ามเปลี่ยน code ของแถวที่มีเรื่องผูกอยู่ (ดู data/catalog.ts)
 *
 * ⚠️ รายการนี้ต้องตามหมวดใหม่เอง ถ้าเพิ่มหมวดย่อยที่เกี่ยวกับตัวเครื่องไปไว้ใต้หมวดอื่น
 *    (เหมือน LIFECYCLE_NEW_PC) แล้วลืมเติมที่นี่ ช่องจะถูกซ่อนจากเรื่องที่ต้องใช้
 *    ผลเสียคือ "ทีมไอทีไม่รู้ว่าเครื่องไหน" ซึ่งแย่กว่าการแสดงช่องที่ไม่จำเป็น
 *    หมวดย่อยใหม่ที่อยู่ใต้ HARDWARE หรือ SR_EQUIPMENT ไม่ต้องเติมอะไร จะแสดงช่องโดยปริยาย
 */

/** หมวดหลักที่ทั้งหมวดเป็นเรื่องตัวอุปกรณ์ — หมวดย่อยทุกใบข้างใต้ถือว่าเกี่ยวข้อง */
const DEVICE_PARENTS: ReadonlySet<string> = new Set([
  'HARDWARE', // เหตุขัดข้อง: คอมพิวเตอร์ จอ เมาส์ เครื่องพิมพ์ มือถือ กล้องวงจรปิด
  'SR_EQUIPMENT', // คำขอ: ขออุปกรณ์ใหม่ / ติดตั้งเครื่องพิมพ์ / หมึก / มือถือ / กล้อง
]);

/** หมวดย่อยที่อยู่ใต้หมวดหลักอื่น แต่ก็เป็นเรื่องตัวเครื่องโดยตรง */
const DEVICE_SUBCATEGORIES: ReadonlySet<string> = new Set([
  'LIFECYCLE_NEW_PC', // เตรียมคอมพิวเตอร์ให้พนักงานใหม่ — เลขทรัพย์สินของเครื่องที่จัดให้
  'SECURITY_DEVICE_LOST', // อุปกรณ์หาย/ถูกลัก — ต้องรู้ว่าเครื่องไหนหาย (แจ้งภายใน 24 ชม.)
]);

/**
 * หมวดย่อยที่อยู่ใต้หมวดอุปกรณ์ แต่ไม่มีตัวเครื่องให้ติดเลข
 *
 *   MOBILE_SIM     ซิมและแพ็กเกจอินเทอร์เน็ต — เป็นบริการ ไม่ใช่ทรัพย์สิน
 *   CCTV_PLAYBACK  ขอดูภาพย้อนหลัง — เรื่องของข้อมูล ไม่ได้เกี่ยวกับกล้องตัวใดตัวหนึ่ง
 */
const NOT_DEVICE_SUBCATEGORIES: ReadonlySet<string> = new Set(['MOBILE_SIM', 'CCTV_PLAYBACK']);

/**
 * ควรแสดงช่องเลขทรัพย์สินหรือไม่
 *
 * @param parentCode รหัสหมวดหลักที่เลือก — null ถ้ายังไม่ได้เลือก
 * @param subCode    รหัสหมวดย่อยที่เลือก — null ถ้าไม่มี หรือหมวดนี้ไม่มีหมวดย่อย
 *
 * ยังไม่เลือกหมวดเลย = ซ่อน — ผู้แจ้งยังไม่ได้บอกว่าเป็นเรื่องอะไร จึงยังไม่รู้ว่าต้องถามหรือเปล่า
 * หมวดย่อยชนะหมวดหลักเสมอ (ข้อยกเว้นใต้หมวดอุปกรณ์ต้องซ่อนได้ ส่วนหมวดย่อยที่ไปอยู่ใต้
 * หมวดอื่นต้องแสดงได้)
 */
export function categoryNeedsAssetTag(
  parentCode: string | null | undefined,
  subCode: string | null | undefined,
): boolean {
  if (subCode) {
    if (NOT_DEVICE_SUBCATEGORIES.has(subCode)) return false;
    if (DEVICE_SUBCATEGORIES.has(subCode)) return true;
  }
  return parentCode ? DEVICE_PARENTS.has(parentCode) : false;
}
