/**
 * กติกาว่าเรื่องใบหนึ่ง "เป็นชนิดไหนได้บ้าง" — กฎล้วน ๆ ไม่มี I/O ไม่มี Nest
 *
 * แยกไฟล์เพราะกฎข้อนี้ต้องถูกบังคับจาก **สองทางเข้า** ที่ไม่รู้จักกัน
 *   1. POST /tickets                      — พนักงานในเครือกรอกฟอร์มเอง
 *   2. POST /support-chat/{id}/ticket     — เจ้าหน้าที่ยกระดับแชทเป็นเรื่อง
 *
 * ถ้าเขียนกฎไว้ทางใดทางหนึ่ง อีกทางจะข้ามไปเงียบ ๆ และไม่มีใครรู้จนกว่าจะเจอ
 * เรื่องชนิดที่ไม่ควรมีอยู่ในฐานข้อมูลจริง — ซึ่งตอนนั้นแก้ย้อนหลังไม่ได้แล้ว
 */

import type { TicketType } from '../../common/constants';

/**
 * ผู้แจ้งที่แท้จริงของเรื่องใบนี้ เท่าที่ระบบรู้
 *
 * ⚠️ ไม่ใช่ "แถวที่ requester_id ชี้ไป"
 *    ตอนยกระดับแชทจาก widget ที่ยังจับคู่กับพนักงานไม่ได้ ระบบใส่ **เจ้าหน้าที่ที่กด**
 *    เป็น requester เพื่อให้คอลัมน์ NOT NULL มีค่า ซึ่งเป็นการลงบัญชี ไม่ใช่ข้อเท็จจริง
 *    ว่าคนถามเป็นพนักงาน ถ้าตัดสินจาก requester_id ตรง ๆ กฎข้อนี้จะถูกข้ามทุกครั้ง
 */
export interface TicketSubmitter {
  /**
   * คนที่ "พิมพ์เรื่องนี้เข้ามา" มีบัญชีพนักงานในเครือจริงหรือไม่
   *
   * false เมื่อเรื่องมาจากช่องแชทของเว็บสาธารณะ และยังจับคู่ผู้เข้าชม
   * กับบัญชีใน Helpdesk ไม่ได้ (support_chat.origin = 'widget' และ requester_id IS NULL)
   */
  isInternalAccount: boolean;
}

export interface TicketTypeDecision {
  ticketType: TicketType;
  /** true = ค่าที่ผู้เรียกขอมาถูกเปลี่ยน ผู้เรียกควรบันทึกไว้ใน log */
  coerced: boolean;
}

/**
 * ชนิดของเรื่องที่ระบบจะใช้จริง
 *
 * กฎของ SA: **เหตุขัดข้องเป็นของพนักงานในเครือเท่านั้น**
 *   เหตุผลคือ Incident แปลว่า "บริการที่ AIDC ให้พนักงานของตัวเองใช้อยู่ ใช้ไม่ได้"
 *   ซึ่งวัดกับ SLA ภายในและนับเข้า KPI ความพร้อมใช้ของระบบงาน
 *   ผู้เข้าชมเว็บภายนอกไม่ได้อยู่ในขอบเขตนั้น เรื่องของเขาคือ "ขอให้ช่วยอะไรบางอย่าง"
 *   = คำขอบริการเสมอ ต่อให้ข้อความจะเล่าว่ามีอะไรพังก็ตาม
 *
 * ⚠️ ดัดค่า ไม่ใช่ปฏิเสธคำขอ (coerce ไม่ใช่ 422) โดยตั้งใจ
 *    ผู้เข้าชมไม่ได้เป็นคนเลือกชนิดของเรื่อง — เจ้าหน้าที่ที่กดยกระดับแชทเป็นคนเลือก
 *    (หรือปล่อยว่างแล้วได้ค่า default 'incident' ของคอลัมน์ติดมา ซึ่งเป็นเส้นทาง
 *    ที่เกิดจริงบ่อยที่สุด) การตอบ 422 จะเป็นการโยนความผิดพลาดเชิงนโยบาย
 *    ให้คนที่แก้อะไรไม่ได้ แล้วเรื่องของผู้เข้าชมจะค้างอยู่ในแชทโดยไม่มีใครรับ
 */
export function resolveTicketType(
  requested: TicketType | undefined,
  submitter: TicketSubmitter,
): TicketTypeDecision {
  // ไม่ได้ระบุมา = ใช้ค่าตั้งต้นเดียวกับคอลัมน์ ticket.ticket_type
  const wanted: TicketType = requested ?? 'incident';

  if (submitter.isInternalAccount) return { ticketType: wanted, coerced: false };

  return {
    ticketType: 'service_request',
    coerced: wanted !== 'service_request',
  };
}
