/**
 * ใครอ่านไฟล์แนบชิ้นนี้ได้
 *
 * ก่อนหน้านี้ฟังก์ชันดาวน์โหลดมีบรรทัด `void scope;` คือไม่ตรวจว่าผู้ขอเป็นใครเลย
 * ผู้ใช้ที่ล็อกอินแล้วคนไหนก็เปิดไฟล์ของใครก็ได้ด้วยการไล่เลข id (1, 2, 3 …)
 * ตอนนั้นยังไม่มีผลเพราะไฟล์ไม่เคยถูกผูกกับเรื่องและไม่มีหน้าจอไหนแสดงมัน
 * แต่เมื่อภาพหน้าจอและวิดีโอของผู้แจ้งปรากฏในหน้ารายละเอียดเรื่อง ช่องนี้คือการรั่วจริง
 * ข้ามบริษัท — จึงต้องปิดก่อนเปิดฟีเจอร์ ไม่ใช่หลัง
 *
 * ฟังก์ชันนี้ล้วน ไม่แตะฐานข้อมูล ให้ผู้เรียกไปหาข้อเท็จจริงมาป้อนเอง
 * เพื่อให้ทุกกติกาข้างล่างมีเทสต์คุมไว้ทีละข้อ
 */

export interface AttachmentFacts {
  uploadedBy: number | null;
  /**
   * เรื่องที่ไฟล์นี้สังกัด — ของไฟล์โดยตรง หรือของคอมเมนต์ที่ไฟล์ติดอยู่
   * null = ไฟล์ที่อัปโหลดแล้วยังไม่ถูกผูกกับอะไร (กำลังกรอกฟอร์มอยู่)
   */
  ticketId: number | null;
  /** ไฟล์ติดอยู่กับคอมเมนต์ และคอมเมนต์นั้นเป็นบันทึกภายในของทีม */
  onInternalComment: boolean;
  kbArticleId: number | null;
}

export interface Viewer {
  userId: number;
  /** ถือสิทธิ์อ่านคอมเมนต์ภายใน — ชุดเดียวกับที่หน้ารายละเอียดเรื่องใช้ตัดสิน */
  canSeeInternal: boolean;
}

/**
 * @param ticketVisible เรื่องที่ไฟล์สังกัดอยู่ในขอบเขตสิทธิ์ของผู้ขอหรือไม่
 *                      (ผ่านกติกาเดียวกับหน้ารายการเรื่อง — บริษัท · เหตุความปลอดภัย)
 */
export function canReadAttachment(file: AttachmentFacts, viewer: Viewer, ticketVisible: boolean): boolean {
  // คนที่อัปโหลดเองเปิดไฟล์ของตัวเองได้เสมอ — รวมถึงตอนยังกรอกฟอร์มและไม่ผูกกับเรื่องใด
  if (file.uploadedBy !== null && file.uploadedBy === viewer.userId) return true;

  // ไฟล์ของบทความคลังความรู้ — อ่านได้ทั้งองค์กรเหมือนตัวบทความ (พฤติกรรมเดิม ไม่เปลี่ยน)
  if (file.kbArticleId !== null) return true;

  // ไฟล์ที่ยังไม่ผูกกับอะไร เป็นของคนอัปโหลดคนเดียว คนอื่นไม่มีเหตุผลต้องเห็น
  if (file.ticketId === null) return false;

  if (!ticketVisible) return false;

  /*
   * ไฟล์ในคอมเมนต์ภายในต้องเห็นเฉพาะคนที่เห็นคอมเมนต์นั้น (US-02 AC-3)
   * ถ้าตรวจแค่ว่าเห็นเรื่องได้ ผู้แจ้งจะเปิดรูปที่ทีมไอทีแนบไว้ในบันทึกภายในได้
   * โดยไล่เลข id เอาเอง ทั้งที่หน้าจอซ่อนคอมเมนต์นั้นไว้แล้ว
   */
  if (file.onInternalComment && !viewer.canSeeInternal) return false;

  return true;
}
