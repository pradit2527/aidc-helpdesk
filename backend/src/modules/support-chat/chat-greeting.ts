/** บทสนทนาที่ขยับล่าสุดเกินเวลานี้ถือว่า "ไม่ใช่ของใหม่" แล้ว */
export const GREETING_FRESH_MINUTES = 15;

/**
 * ห้องจาก widget นี้ควรได้ข้อความต้อนรับไหม
 *
 * ⚠️ ข้อนี้มีไว้กันอุบัติเหตุครั้งใหญ่โดยเฉพาะ
 *    ตัวซิงก์กวาดบทสนทนาที่ขยับใน 7 วันที่ผ่านมาทั้งหมด รอบแรกหลังเปิดใช้งาน
 *    จึง "สร้างห้องใหม่" ให้บทสนทนาเก่าหลายสิบรายการพร้อมกัน ถ้าดูแค่ธง created
 *    ข้อความต้อนรับจะถูกยิงเข้าไปในบทสนทนาเก่าของผู้เข้าชมจริงทุกรายการในคราวเดียว
 *
 *    เงื่อนไขเวลาจึงตัดกรณีนั้นทิ้ง — ทักเฉพาะบทสนทนาที่เพิ่งมีความเคลื่อนไหวจริง ๆ
 *    ห้องเก่าที่ไม่ได้ทัก ไม่มีผลอะไร นอกจากไม่ได้ข้อความนี้
 */
export function shouldGreetWidget(
  chat: { created: boolean; status?: string | null; lastActivityAt?: number | null },
  now: Date,
  maxAgeMinutes: number = GREETING_FRESH_MINUTES,
): boolean {
  if (!chat.created) return false;
  if (chat.status !== 'open') return false;

  const seconds = chat.lastActivityAt;
  if (!seconds || !Number.isFinite(seconds)) return false;

  const ageMs = now.getTime() - seconds * 1000;
  // ขยับ "ในอนาคต" = นาฬิกาสองเครื่องไม่ตรงกัน ยังถือว่าใหม่
  return ageMs <= maxAgeMinutes * 60_000;
}
